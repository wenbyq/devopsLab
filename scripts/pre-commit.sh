#!/bin/bash

echo "=== [Pre-commit Hook] Запуск проверки качества кода ==="

# Проверяем, установлен ли линтер flake8 в виртуальном окружении или глобально
if ! python -m flake8 --version &> /dev/null; then
    echo "❌ Ошибка: flake8 не найден. Установите его с помощью: pip install flake8"
    exit 1
fi

# Запускаем линтинг директории src/
echo "Запуск python -m flake8 src/..."
python -m flake8 src/

# Перехватываем код выполнения линтера (0 - ошибок нет, 1 - ошибки найдены)
LINT_STATUS=$?

if [ $LINT_STATUS -ne 0 ]; then
    echo "========================================================="
    echo "❌ [ОТМЕНА КОММИТА] Линтер обнаружил нарушения стиля PEP8."
    echo "Исправьте ошибки, добавьте файлы через 'git add' и повторите коммит."
    echo "========================================================="
    exit 1
else
    echo "✅ [УСПЕХ] Проверка пройдена. Изменения записаны в историю коммитов."
    exit 0
fi

x = 1